TELCO_FILE = "WA_Fn-UseC_-Telco-Customer-Churn.csv"
BANK_FILE = "bank-full.csv"
RETAIL_XLSX = "online_retail_II.xlsx"
RETAIL_CACHE = "online_retail_II_transactions.csv"

RETAIL_HORIZON_DAYS = 90


def _numeric_only(df: pd.DataFrame, cols: list[str]) -> pd.DataFrame:
    return df[[c for c in cols if c in df.columns]].apply(pd.to_numeric, errors="coerce").fillna(0)


# --------------------------------------------------------------------------- synthetic
def load_synthetic() -> dict:
    path = settings.data_path / "consumers_segmented.csv"
    df = pd.read_csv(path)
    return {
        "meta": {
            "id": "synthetic",
            "label": "Synthetic Consumers (ours)",
            "source": "Generated by this project (backend/services/data_generator.py)",
            "license": "n/a",
            "description": "100k simulated consumers with latent archetypes, calibrated class rates and "
                           "hidden noise. Labels are drawn from the generator, so scores show how well the "
                           "pipeline recovers a known process.",
            "rows": len(df),
            "columns": df.shape[1],
        },
        "tasks": {
            "churn": {
                "kind": "classification", "target": "is_churned",
                "X": _numeric_only(df, CHURN_FEATURES), "y": df["is_churned"].astype(int),
                "notes": ["Labels are Bernoulli draws from a hidden probability, so AUC is capped by design."],
            },
            "conversion": {
                "kind": "classification", "target": "converted",
                "X": _numeric_only(df, CONVERSION_FEATURES), "y": df["converted"].astype(int),
                "notes": [],
            },
            "ltv": {
                "kind": "regression", "target": "ltv_actual",
                "X": _numeric_only(df, LTV_FEATURES), "y": df["ltv_actual"].astype(float),
                "notes": ["Model is fit on log1p(LTV); R² is reported on the log scale."],
            },
            "segmentation": {
                "kind": "segmentation",
                "X": _numeric_only(df, NUMERIC_FEATURES),
                "notes": ["Same engineered numeric features the app clusters on."],
            },
        },
    }


# --------------------------------------------------------------------------- telco
def load_telco() -> dict:
    df = pd.read_csv(settings.data_path / TELCO_FILE)
    df["TotalCharges"] = pd.to_numeric(df["TotalCharges"].replace(" ", np.nan), errors="coerce")
    # 11 customers with tenure 0 have a blank TotalCharges: no billing yet.
    df["TotalCharges"] = df["TotalCharges"].fillna(0.0)
    y = (df["Churn"] == "Yes").astype(int)

    feats = df.drop(columns=["customerID", "Churn"])
    X = pd.get_dummies(feats, drop_first=True, dtype=float)

    service_cols = ["PhoneService", "MultipleLines", "OnlineSecurity", "OnlineBackup",
                    "DeviceProtection", "TechSupport", "StreamingTV", "StreamingMovies"]
    seg = pd.DataFrame({
        "tenure": df["tenure"],
        "MonthlyCharges": df["MonthlyCharges"],
        "TotalCharges": df["TotalCharges"],
        "SeniorCitizen": df["SeniorCitizen"],
        "n_services": sum((df[c] == "Yes").astype(int) for c in service_cols),
        "has_internet": (df["InternetService"] != "No").astype(int),
        "fiber": (df["InternetService"] == "Fiber optic").astype(int),
        "contract_months": df["Contract"].map({"Month-to-month": 1, "One year": 12, "Two year": 24}),
        "autopay": df["PaymentMethod"].str.contains("automatic").astype(int),
    })

    return {
        "meta": {
            "id": "telco",
            "label": "Telco Customer Churn (IBM)",
            "source": "IBM sample dataset (Kaggle: blastchar/telco-customer-churn)",
            "license": "See the Kaggle dataset page before redistributing",
            "description": "7,043 telecom customers with contract, services and billing data and a real churn flag.",
            "rows": len(df),
            "columns": df.shape[1],
        },
        "tasks": {
            "churn": {
                "kind": "classification", "target": "Churn", "X": X, "y": y,
                "notes": ["Blank TotalCharges (tenure 0) set to 0.", "Categoricals one-hot encoded."],
            },
            "segmentation": {
                "kind": "segmentation", "X": seg,
                "notes": ["Clusters on tenure, charges, service count and contract. There is no RFM data."],
            },
        },
    }


# --------------------------------------------------------------------------- bank marketing
def load_bank() -> dict:
    df = pd.read_csv(settings.data_path / BANK_FILE, sep=";")
    y = (df["y"] == "yes").astype(int)

    # `duration` (call length) is only known after the call ends, so it leaks the outcome.
    feats = df.drop(columns=["y", "duration"])
    feats["previously_contacted"] = (feats["pdays"] != -1).astype(int)
    feats.loc[feats["pdays"] == -1, "pdays"] = 0
    X = pd.get_dummies(feats, drop_first=True, dtype=float)

    leaky = pd.get_dummies(df.drop(columns=["y"]), drop_first=True, dtype=float)

    seg = pd.DataFrame({
        "age": df["age"],
        "balance": df["balance"],
        "has_housing_loan": (df["housing"] == "yes").astype(int),
        "has_personal_loan": (df["loan"] == "yes").astype(int),
        "in_default": (df["default"] == "yes").astype(int),
        "education": df["education"].map({"primary": 1, "secondary": 2, "tertiary": 3}).fillna(2),
        "married": (df["marital"] == "married").astype(int),
        "campaign": df["campaign"],
        "previous": df["previous"],
    })

    return {
        "meta": {
            "id": "bank",
            "label": "Bank Marketing (UCI)",
            "source": "UCI ML Repository #222 (Moro, Rita & Cortez, 2014)",
            "license": "CC BY 4.0",
            "description": "45,211 outbound marketing calls from a Portuguese bank. Target: did the client "
                           "subscribe to a term deposit.",
            "rows": len(df),
            "columns": df.shape[1],
        },
        "tasks": {
            "conversion": {
                "kind": "classification", "target": "y (term deposit)", "X": X, "y": y,
                "leaky_X": leaky,
                "notes": ["`duration` dropped: it is only known after the call, so it leaks the outcome.",
                          "pdays = -1 recoded to 0 plus a previously_contacted flag."],
            },
            "segmentation": {
                "kind": "segmentation", "X": seg,
                "notes": ["Demographic and financial profile only. There is no behavioural data."],
            },
        },
    }


# --------------------------------------------------------------------------- online retail II
def _load_retail_transactions() -> pd.DataFrame:
    cache = settings.data_path / RETAIL_CACHE
    if cache.exists():
        return pd.read_csv(cache, parse_dates=["InvoiceDate"])

    logger.info("Reading Online Retail II workbook (slow, one-off) ...")
    sheets = pd.read_excel(settings.data_path / RETAIL_XLSX, sheet_name=None, engine="openpyxl")
    raw = pd.concat(sheets.values(), ignore_index=True)
    raw = raw.rename(columns={"Customer ID": "CustomerID"})
    raw = raw.dropna(subset=["CustomerID"])
    raw["CustomerID"] = raw["CustomerID"].astype(int)
    raw["Invoice"] = raw["Invoice"].astype(str)
    raw["InvoiceDate"] = pd.to_datetime(raw["InvoiceDate"])
    raw[["Invoice", "StockCode", "Quantity", "InvoiceDate", "Price", "CustomerID", "Country"]].to_csv(cache, index=False)
    logger.info(f"Cached cleaned transactions → {cache}")
    return pd.read_csv(cache, parse_dates=["InvoiceDate"])


def build_retail_customers(tx: pd.DataFrame, horizon_days: int = RETAIL_HORIZON_DAYS) -> pd.DataFrame:
    """
    Temporal split: features come from transactions before `cutoff`, targets from the
    `horizon_days` after it. Only customers who bought before the cutoff are included.
    """
    tx = tx.copy()
    tx["is_return"] = tx["Invoice"].str.startswith("C")
    tx["amount"] = tx["Quantity"] * tx["Price"]

    end = tx["InvoiceDate"].max()
    cutoff = end - pd.Timedelta(days=horizon_days)

    before = tx[tx["InvoiceDate"] < cutoff]
    after = tx[(tx["InvoiceDate"] >= cutoff) & (~tx["is_return"]) & (tx["amount"] > 0)]

    sales = before[(~before["is_return"]) & (before["amount"] > 0)]
    inv = sales.groupby(["CustomerID", "Invoice"]).agg(
        inv_date=("InvoiceDate", "max"), inv_amount=("amount", "sum"), inv_items=("Quantity", "sum"),
    ).reset_index()

    g = inv.groupby("CustomerID")
    cust = pd.DataFrame({
        "recency_days": (cutoff - g["inv_date"].max()).dt.days,
        "tenure_days": (cutoff - g["inv_date"].min()).dt.days,
        "frequency": g["Invoice"].nunique(),
        "monetary": g["inv_amount"].sum(),
        "avg_order_value": g["inv_amount"].mean(),
        "avg_items_per_order": g["inv_items"].mean(),
    })
    cust["n_products"] = sales.groupby("CustomerID")["StockCode"].nunique()
    cust["n_countries"] = sales.groupby("CustomerID")["Country"].nunique()
    cust["is_uk"] = (sales.groupby("CustomerID")["Country"].first() == "United Kingdom").astype(int)

    returns = before[before["is_return"]].groupby("CustomerID")["amount"].sum().abs()
    cust["return_value"] = returns.reindex(cust.index).fillna(0.0)
    cust["return_ratio"] = cust["return_value"] / cust["monetary"].clip(lower=1.0)

    # Recent activity: purchases in the 90 days before the cutoff
    recent = inv[inv["inv_date"] >= cutoff - pd.Timedelta(days=90)].groupby("CustomerID")
    cust["orders_last_90d"] = recent["Invoice"].nunique().reindex(cust.index).fillna(0)
    cust["spend_last_90d"] = recent["inv_amount"].sum().reindex(cust.index).fillna(0.0)
    cust["purchase_gap_days"] = (cust["tenure_days"] / cust["frequency"].clip(lower=1))

    future_spend = after.groupby("CustomerID")["amount"].sum().reindex(cust.index).fillna(0.0)
    cust["future_spend"] = future_spend
    cust["churned"] = (future_spend == 0).astype(int)
    return cust


def load_retail() -> dict:
    tx = _load_retail_transactions()
    cust = build_retail_customers(tx)
    feat_cols = [c for c in cust.columns if c not in ("future_spend", "churned")]
    X = cust[feat_cols]

    seg = cust[["recency_days", "frequency", "monetary", "avg_order_value", "n_products", "tenure_days"]].copy()
    seg["frequency"] = np.log1p(seg["frequency"])
    seg["monetary"] = np.log1p(seg["monetary"].clip(lower=0))

    return {
        "meta": {
            "id": "retail",
            "label": "Online Retail II (UCI)",
            "source": "UCI ML Repository #502 (Chen, 2012)",
            "license": "CC BY 4.0",
            "description": f"{len(tx):,} transactions from a UK online retailer (2009-2011), aggregated to "
                           f"{len(cust):,} customers. Features use data before a cutoff; churn and LTV targets "
                           f"come from the {RETAIL_HORIZON_DAYS} days after it.",
            "rows": len(tx),
            "columns": tx.shape[1],
        },
        "tasks": {
            "churn": {
                "kind": "classification", "target": f"no purchase in next {RETAIL_HORIZON_DAYS}d",
                "X": X, "y": cust["churned"].astype(int),
                "notes": [f"Temporal split: features before cutoff, label from the following {RETAIL_HORIZON_DAYS} days.",
                          "Cancellations (invoices starting with C) are treated as returns, not purchases."],
            },
            "ltv": {
                "kind": "regression", "target": f"spend in next {RETAIL_HORIZON_DAYS}d",
                "X": X, "y": cust["future_spend"].astype(float),
                "notes": ["Forward-looking target: future spend, not a function of the input features.",
                          "Customers who stop buying contribute 0, so the target is zero-heavy."],
            },
            "segmentation": {
                "kind": "segmentation", "X": seg,
                "notes": ["Classic RFM plus basket breadth and tenure (log-scaled spend and frequency)."],
            },
        },
    }


