"""
Benchmark dataset adapters.

Each adapter turns a raw dataset into a dict of tasks that apply to it:
    {"meta": {...}, "tasks": {"churn": {...}, "segmentation": {...}}}
A task the dataset cannot support is simply absent.

Classification / regression tasks: {"kind", "X", "y", "target", "notes"}
Segmentation tasks:                {"kind": "segmentation", "X", "notes"}
"""

